#!/usr/bin/env bash
# make ui: bring up the local test stack plus tagcess and print the URL/login to open the web UI.
# Prerequisite: `make lab-up` has run (lab Zitadel on the developer's k3s + local Headscale, ADR 0014).
set -euo pipefail

UI_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_DIR="$(cd "$UI_DIR/../.." && pwd)"
# The lab Zitadel host (the developer's lab.env or env; test/lab/lib.sh).
LAB_HOST="$(bash -c '. "$1/test/lab/lib.sh" && printf %s "$LAB_HOST"' _ "$REPO_DIR")"
export HEADSCALE_OIDC_ISSUER="https://$LAB_HOST" # compose.yaml: Headscale's and oauth2-proxy's issuer
COMPOSE_DIR="$REPO_DIR/test/compose"
CONFIG_DIR="$COMPOSE_DIR/.ui"
PAT_FILE="$COMPOSE_DIR/.secrets/lab/bootstrap-pat"

die() { echo "ui: $*" >&2; exit 1; }

[ -s "$PAT_FILE" ] || die "no lab bootstrap PAT at $PAT_FILE; run 'make lab-up' first"
command -v docker >/dev/null || die "docker is required"

# Re-run the idempotent Zitadel seed so .env exists and carries ZITADEL_PROJECT_ID (the project id
# is not a secret and is written to .env by the seed). The action-target URLs are left unset so the
# shared lab's webhook/groups targets are not touched.
echo "ui: seeding the lab Zitadel (idempotent)"
(
  cd "$REPO_DIR"
  env -u TAGCESS_WEBHOOK_URL -u TAGCESS_GROUPS_URL \
    go run ./test/compose/seed/cmd -phase=zitadel -compose-dir=test/compose
)

PROJECT_ID="$(sed -n 's/^ZITADEL_PROJECT_ID=//p' "$COMPOSE_DIR/.env")"
[ -n "$PROJECT_ID" ] || die "ZITADEL_PROJECT_ID not found in $COMPOSE_DIR/.env after seeding"

mkdir -p "$CONFIG_DIR"
cat >"$CONFIG_DIR/config.yaml" <<EOF
# Generated by 'make ui'; gitignored. No secrets: secret files are mounted from .secrets/lab.
data_dir: /var/lib/tagcess
ui:
  socket: /run/tagcess/ui.sock
  socket_group: caddy
hook:
  listen: 127.0.0.1:9443
  signing_key_file: /etc/tagcess/secrets/webhook-signing-key
headscale:
  socket: 127.0.0.1:50444
zitadel:
  issuer: https://$LAB_HOST
  project_id: "$PROJECT_ID"
  key_file: /etc/tagcess/secrets/zitadel-key.json
  oauth2_proxy_app: oauth2-proxy
# Nothing listens on the Caddy admin port below on purpose: a site apply from this UI stack fails
# safely instead of replacing the compose Caddy that serves the interface itself.
caddy:
  admin_url: http://127.0.0.1:1
  caddyfile_path: /var/lib/tagcess/Caddyfile
dns:
  records_path: /var/lib/tagcess/extra-records.json
sync:
  interval: 5m
sites:
  allowed_domains: [example.com, internal.example.org, example.net]
  allowed_targets: [100.64.0.5]
  acme_email: admin@example.invalid
  certificates: [example.com]
  vpn_address: 100.64.0.4
EOF
chmod 600 "$CONFIG_DIR/config.yaml"

# F2-006 (ADR 0013): Headscale's dns.extra_records_path file must exist before headscale
# starts or the container refuses to start (NewExtraRecordsManager). Seeded once, then
# owned by the F2-006 integration tests and tagcess itself.
mkdir -p "$COMPOSE_DIR/dns"
[ -f "$COMPOSE_DIR/dns/extra-records.json" ] || printf '[]\n' >"$COMPOSE_DIR/dns/extra-records.json"

COMPOSE=(docker compose -f "$COMPOSE_DIR/compose.yaml" -f "$COMPOSE_DIR/ui.compose.yaml")
echo "ui: building tagcess and starting the local stack"
"${COMPOSE[@]}" up -d --build --wait

cat <<'EOF'

tagcess UI is up.
  URL:    http://localhost:8080/
  Login:  devops@tagcess.test
  Parola: Tagcess-Test-1!        (lab test user, seed.TestUserPassword)
  Stop:   make ui-down

The first request redirects to the lab Zitadel login. The local UI Caddyfile injects the
`devops` group after the real login (the lab groups-claim Action cannot reach a container),
so any authenticated lab user reaches the interface.
EOF
