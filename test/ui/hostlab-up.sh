#!/usr/bin/env bash
# make hostlab-ui (F3b-022): the `make ui` equivalent that points tagcess at the host lab (F3b-002/003)
# instead of the compose Headscale. It brings the OrbStack systemd container up, installs the helper
# with deploy/hshelper/install.sh (the production path), writes a tagcess config whose hostapply
# directories are the lab's bind mounts and whose headscale address is the loopback gRPC relay, then
# runs the real tagcess binary on the Mac and prints the URLs.
#
# The binary runs in the foreground; Ctrl-C stops it and the local bridge. The host lab keeps running
# (use `make hostlab-down` to remove it). Prerequisite: `make lab-up` has run (lab Zitadel). If the
# compose Headscale is up, pin free HOSTLAB_* ports in the environment first.
set -euo pipefail

UI_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_DIR="$(cd "$UI_DIR/../.." && pwd)"
# The lab Zitadel host (the developer's lab.env or env; test/lab/lib.sh).
LAB_HOST="$(bash -c '. "$1/test/lab/lib.sh" && printf %s "$LAB_HOST"' _ "$REPO_DIR")"
COMPOSE_DIR="$REPO_DIR/test/compose"
CONFIG_DIR="$COMPOSE_DIR/.hostlab-ui"
PAT_FILE="$COMPOSE_DIR/.secrets/lab/bootstrap-pat"
LAB=tagcess-hostlab

die() { echo "hostlab-ui: $*" >&2; exit 1; }
say() { echo "hostlab-ui: $*"; }

[ -s "$PAT_FILE" ] || die "no lab bootstrap PAT at $PAT_FILE; run 'make lab-up' first"
command -v docker >/dev/null || die "docker is required"
command -v go >/dev/null || die "go is required"

# Re-run the idempotent seed so .env carries ZITADEL_PROJECT_ID (no webhook/groups targets touched).
echo "hostlab-ui: seeding the lab Zitadel (idempotent)"
(
  cd "$REPO_DIR"
  env -u TAGCESS_WEBHOOK_URL -u TAGCESS_GROUPS_URL \
    go run ./test/compose/seed/cmd -phase=zitadel -compose-dir=test/compose
)
PROJECT_ID="$(sed -n 's/^ZITADEL_PROJECT_ID=//p' "$COMPOSE_DIR/.env")"
[ -n "$PROJECT_ID" ] || die "ZITADEL_PROJECT_ID not found in $COMPOSE_DIR/.env after seeding"

# Bring the host lab up (reuse a running one) and install the helper.
if [ "$(docker inspect -f '{{.State.Running}}' "$LAB" 2>/dev/null || true)" = "true" ]; then
  say "reusing the running $LAB"
else
  say "starting the host lab"
  "$REPO_DIR/test/hostlab/hostlab.sh" up
fi
STATE="$(docker inspect -f '{{index .Config.Labels "tagcess.hostlab.state"}}' "$LAB")"
[ -n "$STATE" ] || die "could not read the lab state directory"
HTTP_ADDR="$(sed -n 's/^HOSTLAB_HTTP_ADDR=//p' "$STATE/lab.env")"
GRPC_ADDR="$(sed -n 's/^HOSTLAB_GRPC_ADDR=//p' "$STATE/lab.env")"
[ -n "$HTTP_ADDR" ] && [ -n "$GRPC_ADDR" ] || die "lab.env has no addresses"

say "installing the helper (request uid 0, health http://$HTTP_ADDR/health)"
case "$(docker exec "$LAB" uname -m)" in
  aarch64|arm64) GOARCH=arm64 ;;
  x86_64|amd64) GOARCH=amd64 ;;
  *) die "unsupported lab architecture" ;;
esac
HELPER_BIN="$(mktemp -d)/tagcess-hshelper"
( cd "$REPO_DIR" && GOOS=linux GOARCH="$GOARCH" CGO_ENABLED=0 go build -o "$HELPER_BIN" ./cmd/tagcess-hshelper )
SUM="$(shasum -a 256 "$HELPER_BIN" | awk '{print $1}')"
docker cp "$HELPER_BIN" "$LAB:/root/tagcess-hshelper"
# A reused lab still holds the previous deploy/hshelper: `docker cp <dir> /opt/hshelper` into an
# existing directory nests it, so remove the target first.
docker exec "$LAB" rm -rf /opt/hshelper
docker cp "$REPO_DIR/deploy/hshelper" "$LAB:/opt/hshelper"
docker exec "$LAB" /bin/bash /opt/hshelper/install.sh \
  --binary /root/tagcess-hshelper --sha256 "$SUM" --request-uid 0 --health "http://$HTTP_ADDR/health"

# tagcess config: the lab's shared directories and the loopback gRPC relay. No secrets.
mkdir -p "$CONFIG_DIR" "$CONFIG_DIR/data"
SOCK="$CONFIG_DIR/ui.sock"
cat >"$CONFIG_DIR/config.yaml" <<EOF
# Generated by 'make hostlab-ui'; gitignored. No secrets: secret files are read from .secrets/lab.
data_dir: $CONFIG_DIR/data
ui:
  socket: $SOCK
  socket_group: $(id -gn)
hook:
  listen: 127.0.0.1:9443
  signing_key_file: $COMPOSE_DIR/.secrets/lab/webhook-signing-key
headscale:
  socket: $GRPC_ADDR
zitadel:
  issuer: https://$LAB_HOST
  project_id: "$PROJECT_ID"
  key_file: $COMPOSE_DIR/.secrets/lab/zitadel-key.json
hostapply:
  requests_dir: $STATE/requests
  results_dir: $STATE/results
sync:
  interval: 5m
EOF
chmod 600 "$CONFIG_DIR/config.yaml"

say "building tagcess"
( cd "$REPO_DIR" && go build -o "$CONFIG_DIR/tagcess" ./cmd/tagcess )

cat <<EOF

tagcess (host lab) is running.
  URL:     http://$HTTP_ADDR   (Headscale /health; the OIDC login origin for F3b-023)
  UI:      unix socket $SOCK  ('/headscale/config')
  Login:   devops@tagcess.test  /  Tagcess-Test-1!
  Stop:    Ctrl-C (the host lab stays; 'make hostlab-down' removes it)

The interface socket trusts the oauth2-proxy identity headers, so read it with, e.g.:
  curl --unix-socket $SOCK -H 'X-Auth-Request-User: devops' \\
       -H 'X-Auth-Request-Email: devops@tagcess.test' -H 'X-Auth-Request-Groups: devops' \\
       http://tagcess/headscale/config
EOF

exec "$CONFIG_DIR/tagcess" -config "$CONFIG_DIR/config.yaml"
