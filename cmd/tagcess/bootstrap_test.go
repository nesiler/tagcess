// bootstrapGolden is the fresh lab bootstrap Caddyfile (F6-012 AC12, golden part). Regenerate with
// TAGCESS_UPDATE_GOLDEN=1 go test ./cmd/tagcess -run TestBootstrapCaddyfile_LabGolden.
var bootstrapGolden = filepath.Join("..", "..", "deploy", "ansible", "testdata", "caddy_install", "Caddyfile.lab")

func labBootstrap() bootstrapOptions {
	return bootstrapOptions{
		seedPath: filepath.Join("..", "..", "deploy", "f5", "seed-sites.json"), acmeEmail: "admin@lab.example.com", certs: "lab.example.com",
		internalSources: "10.0.0.0/16,127.0.0.1/32,::1/128", sitesImport: "sites/*.caddy",
	}
}

// AC12 (F6-012, golden part): the lab settings render the bootstrap Caddyfile byte for byte like the golden file:
// tagcess's own system blocks, no ownership marker, the sites import line last.
func TestBootstrapCaddyfile_LabGolden(t *testing.T) {
	var out, errb bytes.Buffer
	if code := runBootstrapCaddyfile(labBootstrap(), &out, &errb); code != 0 {
		t.Fatalf("exit %d: %s", code, errb.String())
	}
	got := out.String()
	if os.Getenv("TAGCESS_UPDATE_GOLDEN") == "1" {
		if err := os.MkdirAll(filepath.Dir(bootstrapGolden), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(bootstrapGolden, []byte(got), 0o644); err != nil { // #nosec G306 -- golden file
			t.Fatal(err)
		}
	}
	want, err := os.ReadFile(bootstrapGolden)
	if err != nil {
		t.Fatalf("golden: %v (TAGCESS_UPDATE_GOLDEN=1 once)", err)
	}
	if got != string(want) {
		t.Fatalf("bootstrap differs from %s:\n%s", bootstrapGolden, got)
	}
	for _, w := range []string{"auth.lab.example.com {", "hs.lab.example.com {", "tls /etc/letsencrypt/live/lab.example.com/fullchain.pem"} {
		if !strings.Contains(got, w) {
			t.Errorf("bootstrap lacks %q", w)
		}
	}
	if strings.Contains(got, "Generated by tagcess") {
		t.Error("the bootstrap carries tagcess's ownership marker (caddy_ui and preflight would treat it as imported)")
	}
	if !strings.HasSuffix(got, "\nimport sites/*.caddy\n") {
		t.Error("the sites import line is not last")
	}
}

func TestBootstrapCaddyfile_Errors(t *testing.T) {
	cases := map[string]func(*bootstrapOptions){
		"no seed":       func(o *bootstrapOptions) { o.seedPath = "" },
		"missing seed":  func(o *bootstrapOptions) { o.seedPath = filepath.Join(t.TempDir(), "none.json") },
		"bad import":    func(o *bootstrapOptions) { o.sitesImport = "sites/*.caddy {" },
		"spaced import": func(o *bootstrapOptions) { o.sitesImport = "a b" },
		"bad email":     func(o *bootstrapOptions) { o.acmeEmail = "x y" },
	}
	for name, mutate := range cases {
		t.Run(name, func(t *testing.T) {
			o := labBootstrap()
			mutate(&o)
			var out, errb bytes.Buffer
			if code := runBootstrapCaddyfile(o, &out, &errb); code != 1 || out.Len() != 0 {
				t.Fatalf("want exit 1 and no output, got %d %q", code, out.String())
			}
		})
	}
	// A role or open site in the seed is refused: on a fresh host nothing narrows its non-tailnet branch yet.
	seed := filepath.Join(t.TempDir(), "seed.json")
	if err := os.WriteFile(seed, []byte(`{"sites":[{"hosts":["app.lab.example.com"],"kind":"role","roles":["devops"],"cert":"auto","target":"k8s"}]}`), 0o600); err != nil {
		t.Fatal(err)
	}
	o := labBootstrap()
	o.seedPath = seed
	if _, err := bootstrapCaddyfile(o); err == nil || !strings.Contains(err.Error(), "system sites only") {
		t.Fatalf("a role site was rendered: %v", err)
	}
	o = labBootstrap()
	o.sitesImport = ""
	text, err := bootstrapCaddyfile(o)
	if err != nil || strings.Contains(text, "import sites") {
		t.Fatalf("no import line wanted: %v", err)
	}
}

// The flag is wired without -config.
func TestRun_BootstrapCaddyfileFlag(t *testing.T) {
	o := labBootstrap()
	var out, errb bytes.Buffer
	code := run([]string{"-bootstrap-caddyfile", "-seed", o.seedPath, "-acme-email", o.acmeEmail, "-certs", o.certs,
		"-zitadel-internal-sources", o.internalSources}, &out, &errb)
	want, _ := bootstrapCaddyfile(o)
	if code != 0 || out.String() != want {
		t.Fatalf("exit %d, stderr %s", code, errb.String())
	}
}
