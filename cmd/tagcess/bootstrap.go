package main

import (
	"fmt"
	"io"
	"os"
	"strings"

	"github.com/nesiler/tagcess/internal/render"
	"github.com/nesiler/tagcess/internal/site"
)

// The fresh-mode bootstrap Caddyfile (F6-012 caddy_install, [Ö] öneri 14): the seed's system sites rendered by the
// same renderer the first-import parity gate compares against, so a fresh host starts at parity 0. tagcess's
// ownership marker is left out (tagcess owns the file only after its first import), and the file ends with the
// import line of the sites directory, where caddy_ui puts the UI block (the existing installation layout). Read-only: it reads
// the seed file and prints; no network call, no other file.

// bootstrapHeader replaces the renderer's ownership marker.
const bootstrapHeader = "# tagcess installer bootstrap (caddy_install). tagcess takes this file over at its first import.\n"

type bootstrapOptions struct {
	seedPath        string
	acmeEmail       string
	certs           string // comma-separated certificate names under /etc/letsencrypt/live
	internalSources string // comma-separated: the zitadel template's internal sources
	sitesImport     string // import line target ("" = none)
}

func splitList(s string) []string {
	var out []string
	for _, v := range strings.Split(s, ",") {
		if v = strings.TrimSpace(v); v != "" {
			out = append(out, v)
		}
	}
	return out
}

func runBootstrapCaddyfile(o bootstrapOptions, stdout, stderr io.Writer) int {
	text, err := bootstrapCaddyfile(o)
	if err != nil {
		_, _ = fmt.Fprintf(stderr, "tagcess: bootstrap caddyfile: %v\n", err)
		return 1
	}
	_, _ = io.WriteString(stdout, text)
	return 0
}

func bootstrapCaddyfile(o bootstrapOptions) (string, error) {
	if o.seedPath == "" {
		return "", fmt.Errorf("-seed is required")
	}
	data, err := os.ReadFile(o.seedPath) // #nosec G304 -- operator-provided path
	if err != nil {
		return "", err
	}
	sites, err := site.PrepareSeed(data, site.SeedOptions{ZitadelInternalSources: splitList(o.internalSources)})
	if err != nil {
		return "", err
	}
	// Fail safe: a fresh host has neither WireGuard nor nftables, so the S-06-open snippet would pass every non-tailnet
	// source straight to a role or open site. The bootstrap carries only system sites; the others are added from the
	// UI after tagcess's first import.
	for i, st := range sites {
		if st.Kind != site.KindSystem {
			return "", fmt.Errorf("seed site %d (%s) is not a system site: the fresh bootstrap renders system sites only; add it from the UI after the first import", i, strings.Join(st.Hosts, ","))
		}
	}
	// The first-import gate renders with the S-06 key open (today's behaviour); so does the bootstrap.
	text, err := render.RenderCaddyfile(sites, render.CaddyConfig{ACMEEmail: o.acmeEmail, S06Open: true, Certs: splitList(o.certs)})
	if err != nil {
		return "", err
	}
	marker, _, ok := strings.Cut(text, "\n")
	if !ok || !strings.HasPrefix(marker, "# Generated by tagcess") {
		return "", fmt.Errorf("unexpected render header %q", marker)
	}
	text = bootstrapHeader + strings.TrimPrefix(text, marker+"\n")
	if o.sitesImport != "" {
		if strings.ContainsAny(o.sitesImport, " \t\n{}\"") {
			return "", fmt.Errorf("-sites-import %q: one path or glob without spaces or braces", o.sitesImport)
		}
		text += "\nimport " + o.sitesImport + "\n"
	}
	return text, nil
}
