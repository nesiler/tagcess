// The fixed Caddyfile header (ADR 0010): a generated marker, the global block
// and the three snippets whose text is today's Caddyfile text. The only part
// that varies is the snippet tail branch: with the S-06 key closed the
// tailnet-outside source gets "respond 403" instead of the open "import k8s"
// (S-06.2); the @api exemption branch never changes.

const caddyMarker = "# Generated by tagcess. Do not edit; every apply rewrites this file from the site records.\n"

// K8sUpstream is the default upstream of the (k8s) snippet, the target every role site proxies to
// (CaddyConfig.K8sUpstream overrides it; an existing installation's Traefik internal entrypoint listens on :8443).
const K8sUpstream = "https://100.64.0.5"

// GateUpstream is the default address of the oauth2-proxy gate (CaddyConfig.GateUpstream overrides it).
const GateUpstream = "127.0.0.1:4180"

// caddyTail is the last handle branch of the vpn_site snippets, the one that
// serves every source outside the tailnet. S-06.2 swaps its body.
const (
	caddyTailOpen   = "\thandle {\n\t\timport k8s\n\t}\n"
	caddyTailClosed = "\thandle {\n\t\trespond 403\n\t}\n"
)

// caddyForbiddenPage is the 403 page of a signed-in user without the site role. It is fixed text:
// no request value is echoed (the Host header is user input) and it has no braces, which Caddy
// would read as placeholders. The link signs the oauth2-proxy session out and returns to the site.
func caddyForbiddenPage(signOut string) string {
	return `<!doctype html><html lang="tr"><head><meta charset="utf-8">` +
		`<meta name="viewport" content="width=device-width,initial-scale=1"><title>Erişim yok</title></head>` +
		`<body style="font-family:system-ui,sans-serif;max-width:32rem;margin:15vh auto;padding:0 1rem;text-align:center">` +
		`<h1 style="font-size:1.4rem">Bu siteye erişim yetkiniz yok</h1>` +
		`<p>Bu site yalnızca yetkili rol sahiplerine açıktır. Hesabınıza yetkili rolün atanmasını isteyin ` +
		`veya başka bir hesapla giriş yapın.</p>` +
		`<p><a href="` + signOut + `">Başka hesapla giriş yap</a></p></body></html>`
}

// caddySnippetAuthFlow is the shared role-control flow of the vpn_site
// snippets (oauth2-proxy forward_auth, fixed text).
func caddySnippetAuthFlow(signOut, gate, tailnet string) string {
	return "\t@tailnet remote_ip " + tailnet + "\n" +
		"\thandle @tailnet {\n" +
		"\t\thandle /oauth2/* {\n" +
		"\t\t\treverse_proxy " + gate + "\n" +
		"\t\t}\n" +
		"\t\thandle {\n" +
		"\t\t\tforward_auth " + gate + " {\n" +
		"\t\t\t\turi /oauth2/auth?allowed_groups={args[1]}\n" +
		"\t\t\t\t@giris_yok status 401\n" +
		"\t\t\t\thandle_response @giris_yok {\n" +
		"\t\t\t\t\tredir * /oauth2/start?rd={scheme}://{host}{uri}\n" +
		"\t\t\t\t}\n" +
		"\t\t\t\t@yetki_yok status 403\n" +
		"\t\t\t\thandle_response @yetki_yok {\n" +
		"\t\t\t\t\theader Content-Type \"text/html; charset=utf-8\"\n" +
		"\t\t\t\t\trespond `" + caddyForbiddenPage(signOut) + "` 403\n" +
		"\t\t\t\t}\n" +
		"\t\t\t}\n" +
		"\t\t\timport k8s\n" +
		"\t\t}\n" +
		"\t}\n"
}

const caddySnippetTLS = "\ttls /etc/letsencrypt/live/{args[0]}/fullchain.pem /etc/letsencrypt/live/{args[0]}/privkey.pem\n"

// caddySnippets renders the fixed snippet section for the S-06 key state. The
// open-key text is byte-identical to the reference Caddyfile
// (testdata/caddy-reference-snippets.caddy). noTLS adds the no-tls variants
// (S-07.1): a site whose cert:auto cannot resolve renders through them, so a
// missing certificate never blocks the record and Caddy never provisions a
// path that does not exist. Unused snippets produce no adapt JSON, so the
// first-import parity is unaffected.
func caddySnippets(s06open, noTLS bool, signOut, upstream, gate, tailnet string) string {
	authFlow := caddySnippetAuthFlow(signOut, gate, tailnet)
	tail := caddyTailOpen
	if !s06open {
		tail = caddyTailClosed
	}
	var b strings.Builder
	b.WriteString("(k8s) {\n")
	b.WriteString("\treverse_proxy " + upstream + " {\n")
	b.WriteString("\t\theader_up Host {http.request.host}\n")
	b.WriteString("\t\theader_up X-Forwarded-Host {http.request.host}\n")
	b.WriteString("\t\theader_up X-Forwarded-Proto https\n")
	b.WriteString("\t\theader_up X-Forwarded-Port 443\n")
	b.WriteString("\n")
	b.WriteString("\t\ttransport http {\n")
	b.WriteString("\t\t\ttls_insecure_skip_verify\n")
	b.WriteString("\t\t}\n")
	b.WriteString("\t}\n")
	b.WriteString("}\n")
	b.WriteString("\n")
	b.WriteString("(vpn_site) {\n")
	b.WriteString(caddySnippetTLS)
	b.WriteString("\n")
	b.WriteString(authFlow)
	b.WriteString("\n")
	b.WriteString(tail)
	b.WriteString("}\n")
	b.WriteString("\n")
	b.WriteString("(vpn_site_api) {\n")
	b.WriteString(caddySnippetTLS)
	b.WriteString("\n")
	b.WriteString("\thandle @api {\n\t\timport k8s\n\t}\n")
	b.WriteString("\n")
	b.WriteString(authFlow)
	b.WriteString("\n")
	b.WriteString(tail)
	b.WriteString("}\n")
	if noTLS {
		b.WriteString("\n")
		b.WriteString("(vpn_site_nt) {\n")
		b.WriteString(authFlow)
		b.WriteString("\n")
		b.WriteString(tail)
		b.WriteString("}\n")
		b.WriteString("\n")
		b.WriteString("(vpn_site_api_nt) {\n")
		b.WriteString("\thandle @api {\n\t\timport k8s\n\t}\n")
		b.WriteString("\n")
		b.WriteString(authFlow)
		b.WriteString("\n")
		b.WriteString(tail)
		b.WriteString("}\n")
	}
	return b.String()
}

// CaddyConfig carries the Caddyfile inputs that do not come from site
// records: the ACME email for the global block, the S-06 key state and the
// certbot certificate names used to resolve cert:auto (R1: auto means the
// longest wildcard certificate covering the host).
type CaddyConfig struct {
	ACMEEmail string
	// S06Open reports whether the WireGuard key (S-06) is open, i.e. today's
	// behaviour. Closed means: outside the tailnet, role and open sites
	// respond 403 while the @api exemption still passes from every source.
	S06Open bool
	// Certs are the certificate names under /etc/letsencrypt/live; only used
	// to resolve cert:auto.
	Certs []string
	// ZitadelIssuer, GateClientID and LogoutReturnURL build the 403 page's sign-out link (J1,
	// SignOutPath). An empty GateClientID keeps the plain oauth2-proxy sign-out.
	ZitadelIssuer   string
	GateClientID    string
	LogoutReturnURL string
	// K8sUpstream is the (k8s) snippet's upstream, https://host[:port]. Empty means the default
	// K8sUpstream.
	K8sUpstream string
	// AdminGroup is the group the tagcess UI block admits (allowed_groups). Empty means DefaultAdminGroup.
	AdminGroup string
	// GateUpstream is the oauth2-proxy address (host:port) every gate reverse_proxy and forward_auth
	// uses. Empty means the default GateUpstream.
	GateUpstream string
	// TailnetCIDR is the IPv4 tailnet prefix every site matcher admits (tailnet.cidr). Empty means
	// dns.DefaultTailnetCIDR. A value that fails dns.ParseTailnetCIDR fails the render.
	TailnetCIDR string
}

// tailnetCIDR is the checked, canonical tailnet prefix; a bad value is refused, never repaired
// (it decides which source addresses reach the sites).
func (c CaddyConfig) tailnetCIDR() (string, error) {
	p, err := dns.ParseTailnetCIDR(c.TailnetCIDR)
	if err != nil {
		return "", err
	}
	return p.String(), nil
}

// gateUpstream is the checked gate address: a plain host:port only, anything else is refused, never
// repaired (security.md §5).
func (c CaddyConfig) gateUpstream() (string, error) {
	if c.GateUpstream == "" {
		return GateUpstream, nil
	}
	host, port, err := net.SplitHostPort(c.GateUpstream)
	if err != nil || host == "" || !gateHostRe.MatchString(host) || !gatePortOK(port) {
		return "", fmt.Errorf("gate upstream %q: must be host:port", c.GateUpstream)
	}
	return c.GateUpstream, nil
}

// gateHostRe is a DNS name or an IP literal (net.SplitHostPort strips the brackets of an IPv6 one).
var gateHostRe = regexp.MustCompile(`^[A-Za-z0-9._:-]+$`)

func gatePortOK(p string) bool {
	n, err := strconv.Atoi(p)
	return err == nil && n >= 1 && n <= 65535 && strconv.Itoa(n) == p
}

// k8sUpstream is the checked (k8s) upstream: only a plain https origin survives (the snippet's
// transport is TLS), anything else is refused, never repaired (security.md §5).
func (c CaddyConfig) k8sUpstream() (string, error) {
	if c.K8sUpstream == "" {
		return K8sUpstream, nil
	}
	up, err := caddyURL(c.K8sUpstream)
	if err != nil {
		return "", fmt.Errorf("k8s upstream: %w", err)
	}
	// url.Parse keeps an empty query, fragment or port silently; none of them belongs in a dial address.
	if !strings.HasPrefix(up, "https://") || strings.ContainsAny(up, "#?") || strings.HasSuffix(up, ":") {
		return "", fmt.Errorf("k8s upstream: %q must be https://host[:port] (the (k8s) snippet speaks TLS)", up)
	}
	return up, nil
}

// RenderCaddyfile renders the Caddyfile: the fixed header, one block per
// role/open site sorted by first host, then the system site blocks in the fixed
// template order (ADR 0010; system.go). The output is
// deterministic: the same site set always renders the same text regardless of
// input order. Every site value passes its own render check first; a value
// that cannot be written safely is an error, never repaired (security.md §5).
func RenderCaddyfile(sites []site.Site, cfg CaddyConfig) (string, error) {
	email, err := caddyEmail(cfg.ACMEEmail)
	if err != nil {
		return "", fmt.Errorf("caddy render: acme email: %w", err)
	}

	signOut, err := SignOutPath(cfg.ZitadelIssuer, cfg.GateClientID, cfg.LogoutReturnURL)
	if err != nil {
		return "", fmt.Errorf("caddy render: %w", err)
	}
	upstream, err := cfg.k8sUpstream()
	if err != nil {
		return "", fmt.Errorf("caddy render: %w", err)
	}

	gate, err := cfg.gateUpstream()
	if err != nil {
		return "", fmt.Errorf("caddy render: %w", err)
	}

	tailnet, err := cfg.tailnetCIDR()
	if err != nil {
		return "", fmt.Errorf("caddy render: %w", err)
	}

	blocks := make([]string, 0, len(sites))
	systemBlocks := make(map[string]string)
	seenHosts := make(map[string]bool)
	noTLS := false
	for i, s := range sites {
		var block string
		if s.Kind == site.KindSystem {
			if _, dup := systemBlocks[s.SystemTemplate]; dup {
				return "", fmt.Errorf("caddy render: site %d: system_template: %q is used by more than one site", i, s.SystemTemplate)
			}
			block, err = renderCaddySystemSite(s, cfg)
			if err == nil {
				systemBlocks[s.SystemTemplate] = block
			}
		} else {
			noTLS = noTLS || siteNeedsNoTLS(s, cfg.Certs)
			block, err = renderCaddySite(s, cfg)
		}
		if err != nil {
			return "", fmt.Errorf("caddy render: site %d: %w", i, err)
		}
		for _, h := range s.Hosts {
			if seenHosts[h] {
				return "", fmt.Errorf("caddy render: site %d: hosts: %q already belongs to another site", i, h)
			}
			seenHosts[h] = true
		}
		if s.Kind != site.KindSystem {
			blocks = append(blocks, block)
		}
	}
	slices.SortStableFunc(blocks, func(a, b string) int {
		return strings.Compare(caddyBlockHost(a), caddyBlockHost(b))
	})
	// System blocks follow the sorted user sites in the fixed template order (ADR 0010 m.4).
	for _, tmpl := range caddySystemOrder {
		if block := systemBlocks[tmpl]; block != "" {
			blocks = append(blocks, block)
		}
	}

	var out strings.Builder
	out.WriteString(caddyMarker)
	out.WriteString("{\n\temail " + email + "\n}\n")
	out.WriteString("\n")
	out.WriteString(caddySnippets(cfg.S06Open, noTLS, signOut, upstream, gate, tailnet))
	for _, block := range blocks {
		out.WriteString("\n")
		out.WriteString(block)
	}
	return out.String(), nil
}

// caddyBlockHost extracts the first host line of a rendered block for sorting.
func caddyBlockHost(block string) string {
	if i := strings.IndexByte(block, ','); i >= 0 && i < strings.IndexByte(block, '\n') {
		return block[:i]
	}
	return block[:strings.IndexByte(block, '\n')-len(" {")]
}

// renderCaddySite renders one site block. The shape per kind and key state
// follows ADR 0010:
//   - role, no api rules:  import vpn_site <cert> <roles>
//   - role, api rules:     @api line first, then import vpn_site_api
//   - redirects:           before the @api matcher and the import
//   - open, key open:      tls + target (import k8s or a url reverse_proxy)
//   - open, key closed:    tls + @tailnet branch to the target, rest 403
func renderCaddySite(s site.Site, cfg CaddyConfig) (string, error) {
	hosts, err := caddyHosts(s.Hosts)
	if err != nil {
		return "", err
	}
	cert, err := caddyCert(s.Cert, hosts, cfg.Certs)
	if err != nil {
		return "", err
	}
	tailnet, err := cfg.tailnetCIDR()
	if err != nil {
		return "", err
	}
	redirects, err := caddyRedirects(s.Redirects)
	if err != nil {
		return "", err
	}

	if s.SystemTemplate != "" || s.SystemConfig != "" {
		return "", fmt.Errorf("system_template: only system sites carry a template or its config")
	}

	var b strings.Builder
	b.WriteString(strings.Join(hosts, ",\n"))
	b.WriteString(" {\n")

	if s.TargetKind == site.TargetK8s && s.TargetURL != "" {
		return "", fmt.Errorf("target: a k8s target must not carry a url, got %q", s.TargetURL)
	}

	switch s.Kind {
	case site.KindRole:
		if s.TargetKind != site.TargetK8s {
			return "", fmt.Errorf("target: role sites render through the vpn_site snippets and only support the k8s target, got %q", s.TargetKind)
		}
		if len(s.Headers) > 0 {
			return "", fmt.Errorf("headers: the k8s target proxies through the fixed vpn_site snippet; extra header_up lines need a url target")
		}
		api, err := caddyAPILine(s.APIRules)
		if err != nil {
			return "", err
		}
		roles, err := caddyRoles(s.Roles)
		if err != nil {
			return "", err
		}
		for i, r := range redirects {
			if cfg.S06Open {
				b.WriteString(r.line())
			} else {
				// A bare redir is ordered before the snippet's 403 catch-all
				// and would answer a non-tailnet source with a redirect; the
				// tailnet-restricted form keeps the source rule (ADR 0010 m.5).
				b.WriteString(r.tailnet(i, tailnet))
			}
		}
		b.WriteString(api)
		snippet := "vpn_site"
		if api != "" {
			snippet = "vpn_site_api"
		}
		// Without a resolved certificate the block renders through the no-tls
		// variant (S-07.1); the roles argument moves to args[0].
		if cert == "" {
			snippet += "_nt"
			b.WriteString("\timport " + snippet + " " + roles + "\n")
		} else {
			b.WriteString("\timport " + snippet + " " + cert + " " + roles + "\n")
		}

	case site.KindOpen:
		if len(s.Roles) > 0 {
			return "", fmt.Errorf("roles: an open site must not carry roles, got %v", s.Roles)
		}
		if len(s.APIRules) > 0 {
			return "", fmt.Errorf("api_rules: open sites do not carry api exemption rules")
		}
		if cert != "" {
			b.WriteString("\ttls /etc/letsencrypt/live/" + cert + "/fullchain.pem /etc/letsencrypt/live/" + cert + "/privkey.pem\n")
			b.WriteString("\n")
		}
		target, err := caddyTarget(s, 1)
		if err != nil {
			return "", err
		}
		if cfg.S06Open {
			for _, r := range redirects {
				b.WriteString(r.line())
			}
			b.WriteString(target)
		} else {
			// Only the tailnet source may take a redirect; a bare redir would
			// precede the 403 branch and answer a non-tailnet source with it.
			b.WriteString("\t@tailnet remote_ip " + tailnet + "\n")
			b.WriteString("\thandle @tailnet {\n")
			for _, r := range redirects {
				b.WriteString(indentLines(r.line(), 1))
			}
			b.WriteString(indentLines(target, 1))
			b.WriteString("\t}\n")
			b.WriteString("\thandle {\n\t\trespond 403\n\t}\n")
		}

	default:
		return "", fmt.Errorf("kind: %q is not a user site kind", s.Kind)
	}

	b.WriteString("}\n")
	return b.String(), nil
}

// caddyTarget renders the open-site target at the given tab depth: the k8s
// snippet import or a reverse_proxy block for a url target.
func caddyTarget(s site.Site, depth int) (string, error) {
	ind := strings.Repeat("\t", depth)
	switch s.TargetKind {
	case site.TargetK8s:
		if len(s.Headers) > 0 {
			return "", fmt.Errorf("headers: the k8s target proxies through the fixed snippet; extra header_up lines need a url target")
		}
		return ind + "import k8s\n", nil
	case site.TargetURL:
		proxy, err := caddyURLProxy(s.TargetURL, s.TargetTLSInsecure, s.Headers, depth)
		if err != nil {
			return "", err
		}
		return proxy, nil
	default:
		return "", fmt.Errorf("target: unknown target kind %q", s.TargetKind)
	}
}

// caddyURLProxy renders the url-target reverse_proxy. header_up lines are the
// only path user headers may take (site-level header_up is not a Caddy
// directive; verified with caddy v2.8.4 adapt), so headers require this block.
func caddyURLProxy(raw string, insecure bool, headers []site.Header, depth int) (string, error) {
	target, err := caddyURL(raw)
	if err != nil {
		return "", err
	}
	ind := strings.Repeat("\t", depth)
	simple := len(headers) == 0 && (!insecure || !strings.HasPrefix(target, "https://"))
	if simple {
		return ind + "reverse_proxy " + target + "\n", nil
	}
	var b strings.Builder
	b.WriteString(ind + "reverse_proxy " + target + " {\n")
	for _, h := range headers {
		name, err := caddyHeaderName(h.Name)
		if err != nil {
			return "", err
		}
		value, err := caddyHeaderValue(h.Value)
		if err != nil {
			return "", err
		}
		b.WriteString(ind + "\theader_up " + name + " \"" + value + "\"\n")
	}
	if insecure && strings.HasPrefix(target, "https://") {
		b.WriteString(ind + "\ttransport http {\n")
		b.WriteString(ind + "\t\ttls_insecure_skip_verify\n")
		b.WriteString(ind + "\t}\n")
	}
	b.WriteString(ind + "}\n")
	return b.String(), nil
}

// caddyAPILine renders the @api matcher line (ADR 0011): a single
// header_present rule uses the native matcher, everything else is a CEL
// expression with the rules OR-combined in stored order.
func caddyAPILine(rules []site.APIRule) (string, error) {
	if len(rules) == 0 {
		return "", nil
	}
	if len(rules) == 1 && rules[0].Type == site.APIRuleHeaderPresent {
		name, err := caddyAPIHeaderName(rules[0].Value)
		if err != nil {
			return "", err
		}
		return "\t@api header " + name + " *\n", nil
	}
	terms := make([]string, 0, len(rules))
	for i, rule := range rules {
		switch rule.Type {
		case site.APIRuleHeaderPresent:
			name, err := caddyAPIHeaderName(rule.Value)
			if err != nil {
				return "", fmt.Errorf("api_rules[%d]: %w", i, err)
			}
			terms = append(terms, "header({'"+name+"': '*'})")
		case site.APIRulePathRegex:
			pattern, err := caddyCELPattern(rule.Value)
			if err != nil {
				return "", fmt.Errorf("api_rules[%d]: %w", i, err)
			}
			terms = append(terms, "path_regexp('"+pattern+"')")
		default:
			return "", fmt.Errorf("api_rules[%d]: unknown rule type %q", i, rule.Type)
		}
	}
	return "\t@api expression `" + strings.Join(terms, " || ") + "`\n", nil
}

// render-level field checks (security.md §5: a value that did not pass
// validation must not reach the template; the renderer re-checks the rules
// that matter for a safe Caddyfile and refuses instead of repairing).

var (
	caddyLabelRE  = regexp.MustCompile(`^[a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?$`)
	caddyRoleRE   = regexp.MustCompile(`^[a-z0-9_-]{1,32}$`)
	caddyCertRE   = regexp.MustCompile(`^[a-z0-9]([a-z0-9.-]*[a-z0-9])?$`)
	caddyPathRE   = regexp.MustCompile(`^/[A-Za-z0-9/_.-]*$`)
	caddyHeaderRE = regexp.MustCompile(`^[A-Za-z0-9!$%&'.^_|~][A-Za-z0-9!#$%&'*+\-.^_|~]{0,127}$`)
	caddyAPIHdrRE = regexp.MustCompile(`^[A-Za-z0-9-]{1,64}$`)
)

func caddyEmail(email string) (string, error) {
	if email == "" || strings.Count(email, "@") != 1 ||
		strings.ContainsAny(email, " \t\r\n\"'`{}\\") ||
		strings.ContainsFunc(email, func(r rune) bool { return r < 0x20 || r > 0x7e }) {
		return "", fmt.Errorf("%q is not a plain acme email", email)
	}
	return email, nil
}

func caddyHosts(hosts []string) ([]string, error) {
	if len(hosts) == 0 {
		return nil, fmt.Errorf("hosts: at least one host is required")
	}
	seen := make(map[string]bool, len(hosts))
	for _, h := range hosts {
		if h == "" || len(h) > 253 || strings.Contains(h, "*") {
			return nil, fmt.Errorf("hosts: %q is not a lowercase RFC 1123 hostname", h)
		}
		for _, label := range strings.Split(h, ".") {
			if !caddyLabelRE.MatchString(label) {
				return nil, fmt.Errorf("hosts: %q is not a lowercase RFC 1123 hostname", h)
			}
		}
		if seen[h] {
			return nil, fmt.Errorf("hosts: %q is listed twice", h)
		}
		seen[h] = true
	}
	return hosts, nil
}

// caddyCert resolves the certificate name of a site: "le:<name>" verbatim
// after a format check, "auto" as the longest certificate covering every host
// of the site (R1 data model).
func caddyCert(cert string, hosts []string, certs []string) (string, error) {
	switch {
	case strings.HasPrefix(cert, "le:"):
		name := strings.TrimPrefix(cert, "le:")
		if name == "" || len(name) > 253 || strings.Contains(name, "..") || !caddyCertRE.MatchString(name) {
			return "", fmt.Errorf("cert: le:%q is not a safe certificate name", name)
		}
		return name, nil
	case cert == "auto":
		best := ""
		for _, c := range certs {
			if !CertCoversAll(c, hosts) {
				continue
			}
			if len(c) > len(best) || (len(c) == len(best) && (best == "" || c < best)) {
				best = c
			}
		}
		if best == "" {
			// S-07.1: a host no wildcard covers must not block the record. The
			// block renders without a tls line (a missing certificate file
			// would fail Caddy's provisioning for the whole config, verified
			// with caddy v2.8.4); the interface warns instead. The no-tls
			// snippets exist exactly when a block needs them.
			return "", nil
		}
		return best, nil
	default:
		return "", fmt.Errorf("cert: %q is neither auto nor le:<name>", cert)
	}
}

// CertCoversAll reports whether the certificate name covers every host: each host is the
// certificate name itself or a direct subdomain of it (the wildcard semantics of cert:auto).
// A name that is not a safe certificate name and an empty host list cover nothing. The web
// review warning reuses this rule, so the warning and the render cannot drift apart.
func CertCoversAll(cert string, hosts []string) bool {
	if len(hosts) == 0 {
		return false
	}
	if strings.Contains(cert, "..") || !caddyCertRE.MatchString(cert) {
		return false
	}
	for _, h := range hosts {
		if !certCovers(cert, h) {
			return false
		}
	}
	return true
}

// certCovers reports whether one host sits on a certificate: the certificate
// name itself or a direct subdomain of it (wildcard semantics of cert:auto).
func certCovers(cert, host string) bool {
	return host == cert || strings.HasSuffix(host, "."+cert)
}

// UncoveredHosts lists the hosts no certificate in certs covers (S-07.1): the
// review screen warns about them; the site record itself is not blocked. The
// order follows the record.
func UncoveredHosts(certs, hosts []string) []string {
	var out []string
	for _, h := range hosts {
		covered := false
		for _, c := range certs {
			if certCovers(c, h) {
				covered = true
				break
			}
		}
		if !covered {
			out = append(out, h)
		}
	}
	return out
}

// siteNeedsNoTLS reports whether a user site renders without a tls line
// (cert:auto that no certificate resolves); the renderer then includes the
// no-tls snippet variants.
func siteNeedsNoTLS(s site.Site, certs []string) bool {
	if s.Cert != "auto" {
		return false
	}
	for _, c := range certs {
		if CertCoversAll(c, s.Hosts) {
			return false
		}
	}
	return true
}

func caddyRoles(roles []string) (string, error) {
	if len(roles) == 0 {
		return "", fmt.Errorf("roles: a role-controlled site needs at least one role")
	}
	for _, r := range roles {
		if !caddyRoleRE.MatchString(r) {
			return "", fmt.Errorf("roles: %q does not match ^[a-z0-9_-]{1,32}$", r)
		}
	}
	return strings.Join(roles, ","), nil
}

// caddyRedirect is a validated redirect, rendered either as a bare redir line
// or restricted to the tailnet source (S-06 closed).
type caddyRedirect struct {
	source string
	target string
	code   int
}

func (r caddyRedirect) line() string {
	return "\tredir " + r.source + " " + r.target + " " + strconv.Itoa(r.code) + "\n"
}

// tailnet renders the redirect restricted to the tailnet source with the
// S-06 key closed. A bare redir is a directive ordered before the 403
// catch-all, so it would answer a non-tailnet source with a redirect; the
// combined remote_ip+path matcher keeps every outside source at 403. The
// matcher name is unique per site (i is the redirect index).
func (r caddyRedirect) tailnet(i int, cidr string) string {
	name := "@redir" + strconv.Itoa(i)
	return "\t" + name + " {\n" +
		"\t\tremote_ip " + cidr + "\n" +
		"\t\tpath " + r.source + "\n" +
		"\t}\n" +
		"\tredir " + name + " " + r.target + " " + strconv.Itoa(r.code) + "\n"
}

func caddyRedirects(redirects []site.Redirect) ([]caddyRedirect, error) {
	out := make([]caddyRedirect, 0, len(redirects))
	for i, r := range redirects {
		if strings.HasPrefix(r.Target, "//") {
			return nil, fmt.Errorf("redirects[%d]: target %q is not a site path", i, r.Target)
		}
		if !caddyPathRE.MatchString(r.Source) {
			return nil, fmt.Errorf("redirects[%d]: source %q does not match the path rule", i, r.Source)
		}
		switch code := r.Code; code {
		case 301, 302, 307, 308:
		default:
			return nil, fmt.Errorf("redirects[%d]: code %d is not 301/302/307/308", i, code)
		}
		target := r.Target
		switch {
		case strings.HasPrefix(target, "//"):
			return nil, fmt.Errorf("redirects[%d]: target %q is not a site path", i, r.Target)
		case strings.HasPrefix(target, "/"):
			if !caddyPathRE.MatchString(target) {
				return nil, fmt.Errorf("redirects[%d]: target %q does not match the path rule", i, r.Target)
			}
		case strings.HasPrefix(target, "http://"), strings.HasPrefix(target, "https://"):
			if err := caddyURLRedirect(target); err != nil {
				return nil, fmt.Errorf("redirects[%d]: target: %w", i, err)
			}
		default:
			if err := siteHostname(target); err != nil {
				return nil, fmt.Errorf("redirects[%d]: target: %w", i, err)
			}
		}
		out = append(out, caddyRedirect{source: r.Source, target: target, code: r.Code})
	}
	return out, nil
}

// siteHostname re-checks a redirect target hostname.
func siteHostname(host string) error {
	if host == "" || len(host) > 253 {
		return fmt.Errorf("%q is not a lowercase RFC 1123 hostname", host)
	}
	for _, label := range strings.Split(host, ".") {
		if !caddyLabelRE.MatchString(label) {
			return fmt.Errorf("%q is not a lowercase RFC 1123 hostname", host)
		}
	}
	return nil
}

// caddyURLRedirect re-checks an absolute redirect target such as today's
// `redir /setup https://projects.../setup/ 308` (R1 B-01): scheme, a plain
// hostname, an optional port and a site path — nothing else survives.
func caddyURLRedirect(raw string) error {
	rest, ok := strings.CutPrefix(raw, "https://")
	if !ok {
		rest, ok = strings.CutPrefix(raw, "http://")
	}
	if !ok || rest == "" {
		return fmt.Errorf("%q is not an absolute http(s) target", raw)
	}
	host := rest
	if i := strings.IndexByte(host, '/'); i >= 0 {
		host, rest = host[:i], rest[i:]
	} else {
		rest = ""
	}
	if i := strings.LastIndexByte(host, ':'); i >= 0 {
		port := host[i+1:]
		if strings.Contains(host[:i], ":") || !caddyPortInRange(port) {
			return fmt.Errorf("port %q is not valid", port)
		}
		host = host[:i]
	}
	if err := siteHostname(host); err != nil {
		return err
	}
	if rest != "" && !caddyPathRE.MatchString(rest) {
		return fmt.Errorf("path %q does not match the path rule", rest)
	}
	return nil
}

// caddyPortInRange reports whether p is a plain decimal port in 1..65535.
// strconv.Atoi alone would accept "+80" and " 80", which would end up in the
// generated text verbatim (F2-004 review).
func caddyPortInRange(p string) bool {
	if p == "" || len(p) > 5 || strings.IndexFunc(p, func(r rune) bool { return r < '0' || r > '9' }) >= 0 {
		return false
	}
	n, err := strconv.Atoi(p)
	return err == nil && n >= 1 && n <= 65535
}

// caddyURL re-checks a url target: only scheme://host:port survives, and only
// with a plain character set (mirrors the store validation; anything else
// would fail /load after the record is stored).
func caddyURL(raw string) (string, error) {
	if strings.ContainsFunc(raw, func(r rune) bool {
		return r < 0x20 || r > 0x7e || r == '`' || r == '"' || r == '\'' || r == '{' || r == '}' || r == '\\'
	}) {
		return "", fmt.Errorf("target: url %q contains an unsafe character", raw)
	}
	u, err := url.Parse(raw)
	if err != nil {
		return "", fmt.Errorf("target: url %q does not parse: %w", raw, err)
	}
	if (u.Scheme != "http" && u.Scheme != "https") || u.Host == "" || u.User != nil ||
		u.Path != "" || u.RawQuery != "" || u.Fragment != "" {
		return "", fmt.Errorf("target: url %q is not scheme://host[:port]", raw)
	}
	if p := u.Port(); p != "" && !caddyPortInRange(p) {
		return "", fmt.Errorf("target: port %q is not in 1..65535", p)
	}
	return raw, nil
}

// caddyHeaderName re-checks an extra header name with the store rule: an RFC
// 7230 token whose first character cannot double as a Caddyfile operation
// prefix ("+" add, "-" delete), a comment start ("#") or a quote/backtick.
func caddyHeaderName(name string) (string, error) {
	if !caddyHeaderRE.MatchString(name) {
		return "", fmt.Errorf("headers: name %q is not a plain header token", name)
	}
	return name, nil
}

func caddyAPIHeaderName(name string) (string, error) {
	if !caddyAPIHdrRE.MatchString(name) {
		return "", fmt.Errorf("header name %q must match ^[A-Za-z0-9-]{1,64}$", name)
	}
	return name, nil
}

// caddyHeaderValue validates an extra header value for the Caddyfile: it must
// be printable ASCII without the characters that would end a quoted Caddyfile
// token or start a placeholder, and it must not end with a backslash — a
// trailing "\" lands in front of the closing quote, where the caddy v2.8.4
// lexer reads \" as an escaped quote and the token never closes. Inside double
// quotes any other backslash passes through verbatim, so no doubling happens.
func caddyHeaderValue(value string) (string, error) {
	if strings.ContainsAny(value, "\"{}") ||
		strings.ContainsFunc(value, func(r rune) bool { return r < 0x20 || r > 0x7e }) {
		return "", fmt.Errorf("header value %q is not printable ASCII without quotes and braces", value)
	}
	if strings.HasSuffix(value, `\`) {
		return "", fmt.Errorf("header value %q must not end with a backslash", value)
	}
	return value, nil
}

// caddyCELPattern escapes a path regex for a CEL string literal: every
// backslash is written twice (a single backslash is a CEL error, R1 B-02).
// The characters that would end the CEL string, the Caddyfile backtick token
// or a placeholder are refused, never repaired.
func caddyCELPattern(pattern string) (string, error) {
	if strings.ContainsAny(pattern, "'`{}") ||
		strings.ContainsFunc(pattern, func(r rune) bool { return r < 0x20 || r == 0x7f }) {
		return "", fmt.Errorf("regex %q contains a forbidden character", pattern)
	}
	return strings.ReplaceAll(pattern, `\`, `\\`), nil
}

// indentLines adds one tab to the start of every non-empty line.
func indentLines(s string, depth int) string {
	ind := strings.Repeat("\t", depth)
	lines := strings.Split(strings.TrimSuffix(s, "\n"), "\n")
	for i, line := range lines {
		lines[i] = ind + line
	}
	return strings.Join(lines, "\n") + "\n"
}
