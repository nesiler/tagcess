package stack

import (
	"fmt"
	"sort"
	"strconv"
	"strings"
)

// Fixed host paths of the managed stack (setup-flow.md §5.2); they are boundaries of the release, not settings.
const (
	stackDir     = "/etc/tagcess/stack"
	secretsDir   = stackDir + "/secrets"
	stackState   = "/var/lib/tagcess-stack"
	headscaleDir = stackDir + "/headscale"
	proxyDir     = stackDir + "/oauth2-proxy"
)

// tagcessBinary is where deploy/Dockerfile installs the binary.
const tagcessBinary = "/usr/local/bin/tagcess"

// Files maps a path relative to /etc/tagcess/stack to its content.
type Files map[string][]byte

// Render validates everything first and returns the compose file and the service configs, or an error and no
// output. Output is byte-for-byte deterministic. It never contains secret values: services read secrets from files
// under /etc/tagcess/stack/secrets/<service>/.
func Render(p Params, m Manifest) (Files, error) {
	if err := p.Validate(); err != nil {
		return nil, err
	}
	if err := m.Validate(); err != nil {
		return nil, err
	}
	files := Files{"compose.yaml": []byte(compose(p, m))}
	if p.has(Headscale) {
		files["headscale/config.yaml"] = []byte(headscaleConfig(p))
	}
	if p.has(OAuth2Proxy) {
		files["oauth2-proxy/oauth2-proxy.cfg"] = []byte(oauth2ProxyConfig(p))
	}
	return files, nil
}

func q(s string) string { return strconv.Quote(s) }

func compose(p Params, m Manifest) string {
	var b strings.Builder
	b.WriteString("# Generated by the tagcess host helper. Do not edit.\nname: tagcess\nservices:\n")
	enabled := []Component{}
	for _, c := range AllComponents() {
		if p.has(c) {
			enabled = append(enabled, c)
		}
	}
	for _, c := range enabled {
		svc := service(c, p)
		fmt.Fprintf(&b, "  %s:\n    image: %s\n    container_name: %s\n    network_mode: host\n    restart: unless-stopped\n",
			c, q(m.Images[c].Ref()), c)
		for _, line := range svc.extra {
			b.WriteString("    " + line + "\n")
		}
		if len(svc.command) > 0 {
			b.WriteString("    command: [" + strings.Join(quoteAll(svc.command), ", ") + "]\n")
		}
		if deps := svc.dependsOn(p); len(deps) > 0 {
			b.WriteString("    depends_on:\n")
			for _, d := range deps {
				fmt.Fprintf(&b, "      %s:\n        condition: service_healthy\n", d)
			}
		}
		if len(svc.volumes) > 0 {
			b.WriteString("    volumes:\n")
			for _, v := range svc.volumes {
				b.WriteString("      - " + q(v) + "\n")
			}
		}
		b.WriteString("    healthcheck:\n      test: [" + strings.Join(quoteAll(svc.health), ", ") + "]\n" +
			"      interval: 10s\n      timeout: 5s\n      retries: 6\n")
	}
	return b.String()
}

func quoteAll(in []string) []string {
	out := make([]string, len(in))
	for i, s := range in {
		out[i] = q(s)
	}
	return out
}

type svcDef struct {
	extra   []string
	volumes []string
	health  []string
	command []string
	deps    []Component
}

func (s svcDef) dependsOn(p Params) []Component {
	var out []Component
	for _, d := range s.deps {
		if p.has(d) {
			out = append(out, d)
		}
	}
	sort.Slice(out, func(i, j int) bool { return out[i] < out[j] })
	return out
}

func gids(ids ...int) []string {
	out := []string{"group_add:"}
	for _, id := range ids {
		out = append(out, "  - "+q(strconv.Itoa(id)))
	}
	return out
}

func service(c Component, p Params) svcDef {
	hardening := []string{"read_only: true", "cap_drop:", "  - ALL", "security_opt:", "  - \"no-new-privileges:true\""}
	switch c {
	case Caddy:
		return svcDef{
			extra:   append(append([]string{}, hardening...), "tmpfs:", "  - /tmp", "cap_add:", "  - NET_BIND_SERVICE"),
			volumes: []string{"/etc/caddy:/etc/caddy:ro", stackState + "/caddy/data:/data", "/run/tagcess:/run/tagcess"},
			health:  []string{"CMD", "caddy", "version"},
		}
	case Headscale:
		extra := append([]string{}, hardening...)
		extra = append(extra, "tmpfs:", "  - /tmp")
		extra = append(extra, gids(p.SocketGID)...)
		return svcDef{
			extra:   extra,
			command: []string{"serve"},
			volumes: []string{
				headscaleDir + ":/etc/headscale:ro",
				secretsDir + "/headscale:/etc/headscale/secrets:ro",
				"/var/lib/headscale:/var/lib/headscale",
				"/var/run/headscale:/var/run/headscale",
				"/var/lib/tagcess-dns:/var/lib/tagcess-dns:ro",
			},
			health: []string{"CMD", "headscale", "health"},
		}
	case Tagcess:
		extra := append([]string{}, hardening...)
		extra = append(extra, "tmpfs:", "  - /tmp")
		extra = append(extra, gids(p.CaddyGID, p.HeadscaleGID, p.SocketGID)...)
		return svcDef{
			extra: extra,
			volumes: []string{
				"/var/lib/tagcess:/var/lib/tagcess",
				"/run/tagcess:/run/tagcess",
				"/etc/caddy:/etc/caddy",
				"/var/run/headscale:/var/run/headscale",
				"/etc/tagcess/config.yaml:/etc/tagcess/config.yaml:ro",
				"/etc/tagcess/secrets:/etc/tagcess/secrets:ro",
			},
			health: []string{"CMD", tagcessBinary, "-config", "/etc/tagcess/config.yaml", "-healthcheck"},
			deps:   []Component{Headscale, Caddy},
		}
	case OAuth2Proxy:
		return svcDef{
			extra:   hardening,
			command: []string{"--config=/etc/oauth2-proxy/oauth2-proxy.cfg"},
			volumes: []string{
				proxyDir + ":/etc/oauth2-proxy:ro",
				secretsDir + "/oauth2-proxy:/run/secrets/oauth2-proxy:ro",
			},
			health: []string{"CMD", "/bin/oauth2-proxy", "--version"},
		}
	default: // Tailscale
		return svcDef{
			extra: []string{
				"devices:", "  - \"/dev/net/tun:/dev/net/tun\"",
				"cap_add:", "  - NET_ADMIN",
				"environment:",
				"  TS_USERSPACE: \"false\"",
				"  TS_STATE_DIR: \"/var/lib/tailscale\"",
				"  TS_SOCKET: \"/var/run/tailscale/tailscaled.sock\"",
			},
			volumes: []string{stackState + "/tailscale:/var/lib/tailscale"},
			health:  []string{"CMD", "tailscale", "--socket=/var/run/tailscale/tailscaled.sock", "status"},
			deps:    []Component{Headscale},
		}
	}
}

func headscaleConfig(p Params) string {
	derp := "false"
	if p.EmbeddedDERP {
		derp = "true"
	}
	var b strings.Builder
	w := func(f string, a ...any) { fmt.Fprintf(&b, f+"\n", a...) }
	w("# Generated by the tagcess host helper when the service is created; later changes go through ADR 0021 patches.")
	w("server_url: %s", q("https://"+p.HeadscaleHost))
	w("listen_addr: %s", q("127.0.0.1:"+strconv.Itoa(p.HeadscalePort)))
	w("metrics_listen_addr: %s", q("127.0.0.1:"+strconv.Itoa(p.HeadscaleMetrics)))
	w("unix_socket: \"/var/run/headscale/headscale.sock\"")
	w("unix_socket_permission: \"0770\"")
	w("noise:\n  private_key_path: \"/var/lib/headscale/noise_private.key\"")
	w("prefixes:\n  v4: %s\n  v6: %s", q(p.PrefixV4), q(p.PrefixV6))
	w("database:\n  type: sqlite\n  sqlite:\n    path: \"/var/lib/headscale/db.sqlite\"")
	w("derp:\n  server:\n    enabled: %s\n    private_key_path: \"/var/lib/headscale/derp_server_private.key\"\n    stun_listen_addr: \"0.0.0.0:3478\"", derp)
	w("  urls:\n    - \"https://controlplane.tailscale.com/derpmap/default\"")
	w("policy:\n  mode: database")
	w("dns:\n  magic_dns: true\n  base_domain: %s\n  extra_records_path: \"/var/lib/tagcess-dns/extra-records.json\"", q(p.MagicDNSDomain))
	w("oidc:\n  issuer: %s\n  client_id: %s\n  client_secret_path: \"/etc/headscale/secrets/oidc_client_secret\"\n  pkce:\n    enabled: true\n  allowed_groups:\n    - %s",
		q(strings.TrimSuffix(p.IssuerURL, "/")), q(p.HeadscaleClientID), q(p.AdminGroup))
	return b.String()
}

func oauth2ProxyConfig(p Params) string {
	var b strings.Builder
	w := func(f string, a ...any) { fmt.Fprintf(&b, f+"\n", a...) }
	w("# Generated by the tagcess host helper. Secrets are read from files, never written here.")
	w("http_address = %s", q("127.0.0.1:"+strconv.Itoa(p.OAuth2ProxyPort)))
	w("provider = \"oidc\"")
	w("oidc_issuer_url = %s", q(strings.TrimSuffix(p.IssuerURL, "/")))
	w("client_id = %s", q(p.ProxyClientID))
	w("client_secret_file = \"/run/secrets/oauth2-proxy/client_secret\"")
	w("cookie_secret_file = \"/run/secrets/oauth2-proxy/cookie_secret\"")
	w("cookie_domains = [%s]", q(p.CookieDomain))
	w("cookie_expire = %s", q(p.CookieLifetime))
	w("cookie_refresh = \"0\"")
	w("redirect_url = %s", q("https://"+p.ProxyHost+"/oauth2/callback"))
	w("code_challenge_method = \"S256\"")
	w("email_domains = [\"*\"]")
	// No global allowed_groups: it would lock out every user who is not an admin from all protected sites. The
	// admin restriction belongs to the tagcess UI gate (a per-site allowed_groups query), the sites keep theirs.
	w("reverse_proxy = true")
	w("set_xauthrequest = true")
	w("upstreams = [\"static://202\"]")
	return b.String()
}
