// AC2: nothing secret is read or copied.
func TestScan_NeverReadsSecrets(t *testing.T) {
	h := fullHost()
	out := scanJSON(t, h)
	if bytes.Contains(out, []byte(canary)) {
		t.Fatalf("a canary secret is in the report:\n%s", out)
	}
	allowed := []string{"/etc/os-release", "/proc/sys/kernel/osrelease", "/proc/cpuinfo", "/proc/meminfo",
		"/etc/caddy/Caddyfile", "/etc/headscale/config.yaml", "/etc/headscale/policy.hujson"}
	for _, p := range h.reads {
		if !slices.Contains(allowed, p) {
			t.Errorf("read of %s is not on the allow-list", p)
		}
	}
	for _, c := range h.ran {
		for _, bad := range []string{"inspect", " env", "printenv", "cat ", "docker exec", "kubectl", "wg showconf", "wg show wg0 private", "get-key"} {
			if strings.Contains(c, bad) {
				t.Errorf("forbidden command %q", c)
			}
		}
	}
}

