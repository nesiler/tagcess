func scanJSON(t *testing.T, h *fakeHost) []byte {
	t.Helper()
	b, err := Scan(h)
	if err != nil {
		t.Fatal(err)
	}
	return b
}

func TestScan_GoldenFullHost(t *testing.T) {
	got := scanJSON(t, fullHost())
	var pretty bytes.Buffer
	if err := json.Indent(&pretty, got, "", "  "); err != nil {
		t.Fatal(err)
	}
	pretty.WriteByte('\n')
	const golden = "testdata/full_host.golden.json"
	if *update {
		if err := os.WriteFile(golden, pretty.Bytes(), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	want, err := os.ReadFile(golden)
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(pretty.Bytes(), want) {
		t.Errorf("report differs from %s (run with -update to rewrite):\n%s", golden, pretty.String())
	}
	if !bytes.Equal(got, scanJSON(t, fullHost())) {
		t.Error("two scans of the same host differ")
	}
}

func TestScan_Kinds(t *testing.T) {
	var r Report
	if err := json.Unmarshal(scanJSON(t, fullHost()), &r); err != nil {
		t.Fatal(err)
	}
	if r.Version != Version || r.Result != ResultComplete {
		t.Fatalf("version %d result %q", r.Version, r.Result)
	}
	kinds := map[Kind]bool{}
	for _, f := range r.Findings {
		kinds[f.Kind] = true
	}
	for _, k := range []Kind{KindHost, KindListener, KindReverseProxy, KindCaddy, KindHeadscale, KindTailscale,
		KindWireGuard, KindIdP, KindK8s, KindDocker, KindContainer, KindOther} {
		if !kinds[k] {
			t.Errorf("no finding of kind %s", k)
		}
	}
}

func TestScan_ListenerOwners(t *testing.T) {
	var r Report
	if err := json.Unmarshal(scanJSON(t, fullHost()), &r); err != nil {
		t.Fatal(err)
	}
	by := map[string]Attrs{}
	for _, f := range r.Findings {
		by[f.Subject] = f.Attrs
	}
	for subject, want := range map[string][2]any{
		"listener/443/tcp":  {"caddy", "process"},
		"listener/8080/tcp": {"other-web", "container"}, // docker-proxy resolved through the published ports
		"listener/3478/udp": {nil, nil},
	} {
		a := by[subject]
		if want[0] == nil {
			if a["listening"] != false {
				t.Errorf("%s listening = %v, want false", subject, a["listening"])
			}
			continue
		}
		if a["owner"] != want[0] || a["owner_kind"] != want[1] {
			t.Errorf("%s = %v, want owner %v (%v)", subject, a, want[0], want[1])
		}
	}
	if a := by["reverse_proxy/443"]; a["product"] != "caddy" || a["version"] != "2.8.4" {
		t.Errorf("reverse_proxy/443 = %v", a)
	}
	if _, ok := by["listener/22/tcp"]; ok {
		t.Error("port 22 is not on the scan list")
	}
}

func TestScan_ProxyProducts(t *testing.T) {
	for _, tc := range []struct{ proc, cmd, out, product, version string }{
		{"nginx", "nginx -v", "nginx version: nginx/1.24.0 (Ubuntu)\n", "nginx", "1.24.0"},
		{"traefik", "traefik version", "Version:      3.1.2\nCodename: x\n", "traefik", "3.1.2"},
		{"haproxy", "haproxy -v", "HAProxy version 2.8.5-1 2024/01/01\n", "haproxy", "2.8.5-1"},
		{"apache2", "apache2 -v", "Server version: Apache/2.4.58 (Ubuntu)\n", "apache", "2.4.58"},
		{"envoy", "", "", "unknown", ""},
	} {
		t.Run(tc.proc, func(t *testing.T) {
			h := &fakeHost{cmds: map[string]string{
				"systemctl list-unit-files --type=service --no-legend --no-pager": "",
				"ss -H -ltunp": `tcp LISTEN 0 1 0.0.0.0:443 0.0.0.0:* users:(("` + tc.proc + `",pid=1,fd=1))`,
			}}
			if tc.cmd != "" {
				h.cmds[tc.cmd] = tc.out
			}
			var r Report
			if err := json.Unmarshal(scanJSON(t, h), &r); err != nil {
				t.Fatal(err)
			}
			for _, f := range r.Findings {
				if f.Subject == "reverse_proxy/443" {
					if v, _ := f.Attrs["version"].(string); f.Attrs["product"] != tc.product || v != tc.version {
						t.Errorf("got %v", f.Attrs)
					}
					return
				}
			}
			t.Error("no reverse_proxy/443 finding")
		})
	}
}

