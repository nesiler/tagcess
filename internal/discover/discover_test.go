var update = flag.Bool("update", false, "rewrite the golden files")

// fakeHost serves fixtures and records every read and command, so tests can assert what was touched.
type fakeHost struct {
	files map[string]string
	dirs  map[string][]string
	cmds  map[string]string // "name arg arg" -> output; a missing key is a missing tool
	gets  map[string]string

	reads []string
	ran   []string
}

func (f *fakeHost) ReadFile(p string) ([]byte, error) {
	f.reads = append(f.reads, p)
	if s, ok := f.files[p]; ok {
		return []byte(s), nil
	}
	return nil, os.ErrNotExist
}

func (f *fakeHost) ReadDir(p string) ([]string, error) {
	if l, ok := f.dirs[p]; ok {
		return l, nil
	}
	return nil, os.ErrNotExist
}

func (f *fakeHost) Exists(p string) bool {
	if _, ok := f.files[p]; ok {
		return true
	}
	_, ok := f.dirs[p]
	return ok
}

func (f *fakeHost) Run(name string, args ...string) (string, error) {
	key := strings.Join(append([]string{name}, args...), " ")
	f.ran = append(f.ran, key)
	if out, ok := f.cmds[key]; ok {
		return out, nil
	}
	return "", errors.New("missing or failed")
}

func (f *fakeHost) RunAs(user, name string, args ...string) (string, error) {
	return f.Run(name, args...)
}

func (f *fakeHost) Get(url string) (int, []byte, error) {
	if b, ok := f.gets[url]; ok {
		return 200, []byte(b), nil
	}
	return 0, nil, errors.New("unreachable")
}

