const (
	caddyfilePath     = "/etc/caddy/Caddyfile"
	caddyAdminConfig  = "http://127.0.0.1:2019/config/"
	headscaleConfig   = "/etc/headscale/config.yaml"
	tagcessMarker     = "# Generated by tagcess"
	wireguardDir      = "/etc/wireguard"
	k3sKubeconfig     = "/etc/rancher/k3s/k3s.yaml"
	rootKubeconfig    = "/root/.kube/config"
	maxPolicyFileSize = 1 << 20
)

// unitOrContainer describes how a service is present: its systemd unit and/or a container of one of the repos.
type presence struct {
	unit      string // unit name, "" when absent
	unitState string
	cont      container
	hasCont   bool
}

func (s *scan) presence(units []string, repos ...string) presence {
	var p presence
	for _, u := range units {
		if s.units[u] {
			p.unit, p.unitState = u, s.unitState(u)
			break
		}
	}
	p.cont, p.hasCont = s.containerFor(repos...)
	return p
}

func (p presence) any() bool { return p.unit != "" || p.hasCont }

// attrs are the fields every service finding has.
func (p presence) attrs() Attrs {
	a := Attrs{"unit": p.unit, "unit_state": p.unitState, "container": "", "container_state": "", "image": ""}
	if p.hasCont {
		a["container"], a["container_state"], a["image"] = p.cont.Name, p.cont.State, p.cont.Image
	}
	return a
}

func (s *scan) scanCaddy() {
	p := s.presence([]string{"caddy"}, "caddy")
	_, binErr := s.h.Run("caddy", "version")
	if !p.any() && binErr != nil {
		return
	}
	a := p.attrs()
	a["caddyfile_path"] = ""
	if out, err := s.h.Run("caddy", "version"); err == nil {
		a["version"] = firstVersion(firstLine(out))
	} else if p.hasCont {
		a["version"] = firstVersion(p.cont.tag())
	}
	a["tagcess_marker"], a["validate"], a["admin_reachable"], a["disk_equals_running"] = false, "unknown", false, "unknown"

	var live []byte
	if st, body, err := s.h.Get(caddyAdminConfig); err == nil && st == 200 {
		a["admin_reachable"], live = true, body
	}
	if s.h.Exists(caddyfilePath) {
		a["caddyfile_path"] = caddyfilePath
		if b, err := s.h.ReadFile(caddyfilePath); err == nil {
			a["tagcess_marker"] = bytes.HasPrefix(b, []byte(tagcessMarker))
		}
		if binErr == nil {
			if _, err := s.h.RunAs("caddy", "caddy", "validate", "--config", caddyfilePath, "--adapter", "caddyfile"); err == nil {
				a["validate"] = "ok"
			} else {
				a["validate"] = "failed"
			}
			if adapted, err := s.h.RunAs("caddy", "caddy", "adapt", "--config", caddyfilePath, "--adapter", "caddyfile"); err == nil && live != nil {
				na, nl := normJSON([]byte(adapted)), normJSON(live)
				a["disk_equals_running"] = "no"
				if na != "" && na == nl {
					a["disk_equals_running"] = "yes"
				}
			}
		}
	}
	s.add(KindCaddy, "caddy/"+subjectVia(p), "unit/container, caddy validate, admin GET /config/", a)
}

func subjectVia(p presence) string {
	if p.unit != "" {
		return "systemd"
	}
	if p.hasCont {
		return "docker"
	}
	return "binary"
}

// normJSON re-encodes JSON with sorted keys (Go sorts map keys) so two documents compare by value.
func normJSON(b []byte) string {
	var v any
	if json.Unmarshal(b, &v) != nil {
		return ""
	}
	n, err := json.Marshal(v)
	if err != nil {
		return ""
	}
	return string(n)
}

// headscaleCfg decodes only the fields the scan reports. Everything else in config.yaml, including the OIDC
// client secret and private key paths, is dropped by the decoder and never copied.
type headscaleCfg struct {
	ServerURL  string `yaml:"server_url"`
	UnixSocket string `yaml:"unix_socket"`
	Policy     struct {
		Mode string `yaml:"mode"`
		Path string `yaml:"path"`
	} `yaml:"policy"`
	Database struct {
		Type string `yaml:"type"`
	} `yaml:"database"`
	OIDC struct {
		Issuer string `yaml:"issuer"`
	} `yaml:"oidc"`
	DNS struct {
		ExtraRecordsPath string `yaml:"extra_records_path"`
	} `yaml:"dns"`
}

var policyRoots = []string{"/etc/headscale/", "/var/lib/headscale/"}

func safePolicyPath(p string) bool {
	if p == "" || path.Clean(p) != p {
		return false
	}
	for _, r := range policyRoots {
		if strings.HasPrefix(p, r) {
			return true
		}
	}
	return false
}

func (s *scan) scanHeadscale() {
	p := s.presence([]string{"headscale"}, "headscale")
	_, binErr := s.h.Run("headscale", "version")
	if !p.any() && binErr != nil {
		return
	}
	a := p.attrs()
	for _, k := range []string{"version", "server_url", "policy_mode", "database_type", "oidc_issuer", "socket", "dns_extra_records_path", "policy_sha256"} {
		a[k] = ""
	}
	a["configtest"], a["policy_check"] = "unknown", "unknown"
	if out, err := s.h.Run("headscale", "version"); err == nil {
		a["version"] = firstVersion(firstLine(out))
	} else if p.hasCont {
		a["version"] = firstVersion(p.cont.tag())
	}
	if b, err := s.h.ReadFile(headscaleConfig); err == nil {
		var c headscaleCfg
		if yaml.Unmarshal(b, &c) == nil {
			a["server_url"], a["policy_mode"], a["database_type"] = cleanURL(c.ServerURL), c.Policy.Mode, c.Database.Type
			a["oidc_issuer"], a["socket"], a["dns_extra_records_path"] = cleanURL(c.OIDC.Issuer), c.UnixSocket, c.DNS.ExtraRecordsPath
		}
		if binErr == nil {
			a["configtest"] = okOrFailed(s.h.RunAs("headscale", "headscale", "-c", headscaleConfig, "configtest"))
			if safePolicyPath(c.Policy.Path) {
				if pb, err := s.h.ReadFile(c.Policy.Path); err == nil && len(pb) <= maxPolicyFileSize {
					sum := sha256.Sum256(pb)
					a["policy_sha256"] = hex.EncodeToString(sum[:])
					a["policy_check"] = okOrFailed(s.h.RunAs("headscale", "headscale", "-c", headscaleConfig, "policy", "check", "-f", c.Policy.Path))
				}
			}
		}
	}
	s.add(KindHeadscale, "headscale/"+subjectVia(p), "unit/container, configtest, policy check", a)
}

func okOrFailed(_ string, err error) string {
	if err != nil {
		return "failed"
	}
	return "ok"
}

func (s *scan) scanTailscale() {
	p := s.presence([]string{"tailscaled"}, "tailscale")
	_, binErr := s.h.Run("tailscale", "version")
	if !p.any() && binErr != nil {
		return
	}
	a := p.attrs()
	a["backend_state"], a["control_url"], a["version"] = "", "", ""
	a["ips"], a["tags"] = []string{}, []string{}
	if out, err := s.h.Run("tailscale", "version"); err == nil {
		a["version"] = firstVersion(firstLine(out))
	}
	if out, err := s.h.Run("tailscale", "status", "--json"); err == nil {
		// Typed decode: auth URLs, node keys and peers are not in the struct and never copied.
		var st struct {
			BackendState string
			Self         struct {
				TailscaleIPs []string
				Tags         []string
			}
		}
		if json.Unmarshal([]byte(out), &st) == nil {
			a["backend_state"], a["ips"], a["tags"] = st.BackendState, nonNil(st.Self.TailscaleIPs), nonNil(st.Self.Tags)
		}
	}
	if out, err := s.h.Run("tailscale", "debug", "prefs"); err == nil {
		var pr struct{ ControlURL string }
		if json.Unmarshal([]byte(out), &pr) == nil {
			a["control_url"] = cleanURL(pr.ControlURL)
		}
	}
	s.add(KindTailscale, "tailscale/"+subjectVia(p), "unit/container, tailscale status --json", a)
}

func nonNil(l []string) []string {
	if l == nil {
		return []string{}
	}
	return l
}

var wgConfName = regexp.MustCompile(`^[A-Za-z0-9_=+.-]{1,40}\.conf$`)

func (s *scan) scanWireGuard() {
	var ifaces []string
	if out, err := s.h.Run("wg", "show", "interfaces"); err == nil {
		ifaces = strings.Fields(out)
		sort.Strings(ifaces)
	}
	peers := map[string]int{}
	for _, i := range ifaces {
		if out, err := s.h.Run("wg", "show", i, "peers"); err == nil {
			peers[i] = len(strings.Fields(out)) // only counted: the output is peer public keys
		}
	}
	// Names of files only; their contents hold private keys and are never opened.
	var files []string
	if names, err := s.h.ReadDir(wireguardDir); err == nil {
		for _, n := range names {
			if wgConfName.MatchString(n) {
				files = append(files, n)
			}
		}
		sort.Strings(files)
	}
	ui := s.presence([]string{"wireguard-ui"}, "wireguard-ui")
	var quick []string
	for u := range s.units {
		if strings.HasPrefix(u, "wg-quick@") {
			quick = append(quick, u)
		}
	}
	sort.Strings(quick)
	if len(ifaces) == 0 && len(files) == 0 && !ui.any() && len(quick) == 0 {
		return
	}
	counts := make([]string, 0, len(ifaces))
	for _, i := range ifaces {
		counts = append(counts, fmt.Sprintf("%s=%d", i, peers[i]))
	}
	s.add(KindWireGuard, "wireguard/host", "wg show interfaces, directory listing", Attrs{
		"interfaces": nonNil(ifaces), "peer_counts": nonNil(counts), "config_files": nonNil(files),
		"quick_units": nonNil(quick), "ui_present": ui.any(),
	})
}

// idps are the identity providers the scan names, by unit or image repository.
var idps = []struct {
	name  string
	units []string
	repos []string
}{
	{"zitadel", []string{"zitadel"}, []string{"zitadel"}},
	{"keycloak", []string{"keycloak"}, []string{"keycloak"}},
	{"authentik", []string{"authentik", "authentik-server"}, []string{"authentik", "server"}},
}

func (s *scan) scanIdP() {
	for _, d := range idps {
		repos := d.repos
		if d.name == "authentik" { // `server` alone is too generic: require the project's own image path
			repos = nil
			for _, c := range s.cont {
				if strings.Contains(c.Image, "authentik") {
					repos = append(repos, c.repo())
				}
			}
		}
		p := s.presence(d.units, repos...)
		if !p.any() {
			continue
		}
		a := p.attrs()
		a["name"] = d.name
		s.add(KindIdP, "idp/"+d.name+"/"+subjectVia(p), "unit or image name", a)
	}
}

func (s *scan) scanK8s() {
	var units []string
	for _, u := range []string{"k3s", "k3s-agent", "kubelet"} {
		if s.units[u] {
			units = append(units, u+"="+s.unitState(u))
		}
	}
	// Existence only: the kubeconfig contents are imported through the narrow UI flow (K-01), never here.
	k3sCfg, rootCfg := s.h.Exists(k3sKubeconfig), s.h.Exists(rootKubeconfig)
	if len(units) == 0 && !k3sCfg && !rootCfg {
		return
	}
	s.add(KindK8s, "k8s/host", "unit presence, file existence", Attrs{
		"units": units, "k3s_kubeconfig_present": k3sCfg, "root_kubeconfig_present": rootCfg,
	})
}

func (s *scan) scanOther() {
	hp := s.presence([]string{"headplane"}, "headplane")
	if hp.any() || s.h.Exists("/etc/headplane") {
		a := hp.attrs()
		a["config_dir_present"] = s.h.Exists("/etc/headplane")
		s.add(KindOther, "other/headplane", "unit, container, directory", a)
	}
	if s.units["dnsmasq"] {
		s.add(KindOther, "other/dnsmasq", "unit", Attrs{"unit": "dnsmasq", "unit_state": s.unitState("dnsmasq")})
	}
	conf := s.h.Exists("/etc/nftables.conf")
	if s.units["nftables"] || conf {
		a := Attrs{"config_present": conf, "unit": "", "unit_state": ""}
		if s.units["nftables"] {
			a["unit"], a["unit_state"] = "nftables", s.unitState("nftables")
		}
		s.add(KindOther, "other/nftables", "unit, file existence", a)
	}
}
