//go:build installer

package installer

import (
	"strings"
	"testing"

	"github.com/nesiler/tagcess/test/adopttarget"
)

var caddyRoot = []string{"/etc/caddy"}

// AC20, AC22 (F6-005): on the adopt shape the block goes to sites/tagcess.caddy only (the Caddyfile and the 20
// site files keep their sha256), Caddy validates and reloads; a request from outside the tailnet gets 403. The
// second run changes nothing.
func TestCaddyUI_AddsBlockOnlyThisFile(t *testing.T) {
	t.Parallel()
	tg := adopttarget.Up(t, "adopt")
	before := tg.Checksums(t, caddyRoot)
	home := t.TempDir()
	mustRun(t, tg, home, adopttarget.AdoptVars(), nil, "caddy_ui")
	diff := adopttarget.DiffChecksums(before, tg.Checksums(t, caddyRoot))
	if len(diff) != 1 || diff[0] != "+ /etc/caddy/sites/tagcess.caddy" {
		t.Fatalf("changes in /etc/caddy: %v", diff)
	}
	tg.Sh(t, "curl -fsS http://127.0.0.1:2019/config/ | grep -q tagcess.c.example.test")
	noChanges(t, tg, mustRun(t, tg, home, adopttarget.AdoptVars(), nil, "caddy_ui"))

	t.Run("TestCaddyUI_NonTailnet403", func(t *testing.T) {
		code := strings.TrimSpace(tg.Sh(t, "curl -sk -o /dev/null -w '%{http_code}' --resolve tagcess.c.example.test:443:127.0.0.1 https://tagcess.c.example.test/"))
		if code != "403" {
			t.Fatalf("a non-tailnet source got %s, want 403", code)
		}
	})
}

// AC21 (F6-005): a failed caddy validate removes the block again and never reloads.
func TestCaddyUI_ValidateFailKeepsOld(t *testing.T) {
	t.Parallel()
	tg := adopttarget.Up(t, "adopt")
	before := tg.Checksums(t, caddyRoot)
	running := tg.Sh(t, "curl -fsS http://127.0.0.1:2019/config/ | sha256sum")
	vars := adopttarget.Merge(adopttarget.AdoptVars(), map[string]any{"tagcess_host": "bad{host"})
	res := runSite(t, tg, t.TempDir(), vars, nil, "caddy_ui")
	if res.ExitCode == 0 || !strings.Contains(res.Output, "caddy validate arayüz bloğuyla düştü") {
		t.Fatalf("want a validation stop:\n%s", res.Output)
	}
	if d := adopttarget.DiffChecksums(before, tg.Checksums(t, caddyRoot)); len(d) > 0 {
		t.Fatalf("/etc/caddy changed:\n%s", strings.Join(d, "\n"))
	}
	if after := tg.Sh(t, "curl -fsS http://127.0.0.1:2019/config/ | sha256sum"); after != running {
		t.Fatal("Caddy's running config changed")
	}
}

// AC23 (F6-005): once tagcess owns the Caddyfile (first import done) the phase writes no Caddy file.
func TestCaddyUI_SkipsWhenTagcessOwnsCaddyfile(t *testing.T) {
	t.Parallel()
	tg := adopttarget.Up(t, "adopt")
	// tagcess writes this marker as the first line of every Caddyfile it renders.
	tg.Sh(t, `sed -i '1i # Generated by tagcess. Do not edit; every apply rewrites this file from the site records.' /etc/caddy/Caddyfile && systemctl reload caddy`)
	before := tg.Checksums(t, caddyRoot)
	res := mustRun(t, tg, t.TempDir(), adopttarget.AdoptVars(), nil, "caddy_ui")
	if !strings.Contains(res.Output, "Caddyfile'ın sahibi tagcess") {
		t.Fatalf("not reported:\n%s", res.Output)
	}
	if d := adopttarget.DiffChecksums(before, tg.Checksums(t, caddyRoot)); len(d) > 0 {
		t.Fatalf("Caddy files changed:\n%s", strings.Join(d, "\n"))
	}
}
