#!/usr/bin/env bash
# Generates Codex custom agents (.codex/agents/*.toml) from .agents/agents/*.md (the single source).
# Usage: gen-codex-agents.sh [OUT_DIR]   (default .codex/agents)
set -eu
cd "$(dirname "$0")/.."
. scripts/lib.sh

out=${1:-.codex/agents}
mkdir -p "$out"
rm -f "$out"/*.toml

toml_str() { printf '%s' "$1" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g'; }

for f in .agents/agents/*.md; do
  name=$(fm "$f" name); desc=$(fm "$f" description); sandbox=$(fm "$f" codex_sandbox)
  [ -n "$name" ] && [ -n "$desc" ] || { echo "agents: $f needs name and description" >&2; exit 1; }
  instructions=$(body "$f")
  if printf '%s' "$instructions" | grep -q "'''"; then
    echo "agents: $f body must not contain ''' (TOML literal string delimiter)" >&2; exit 1
  fi
  {
    echo "# GENERATED by scripts/gen-codex-agents.sh from $f. Do not edit; run 'make agents'."
    echo "name = \"$(toml_str "$name")\""
    echo "description = \"$(toml_str "$desc")\""
    echo "sandbox_mode = \"${sandbox:-read-only}\""
    echo "developer_instructions = '''"
    printf '%s\n' "$instructions" | sed -e '/./,$!d'
    echo "'''"
  } > "$out/$name.toml"
done
echo "agents: generated $(ls "$out"/*.toml | wc -l | tr -d ' ') files in $out"
