#!/usr/bin/env bash
# TestGenerate_UpToDate : `make generate` produces templ and sqlc output, and
# `make generate-check` catches stale generated code. Runs in a throwaway copy of the repo.
set -u
cd "$(dirname "$0")/.."
root=$(pwd)
fx=scripts/testdata/generate
tmp=$(mktemp -d) || exit 1
trap 'rm -rf "$tmp"' EXIT
fail=0
bad() { echo "generate-test: FAIL: $1" >&2; fail=1; }

# Copy tracked and new (non-ignored) files that still exist.
git ls-files --cached --others --exclude-standard -z |
  while IFS= read -r -d '' f; do [ -e "$f" ] && printf '%s\0' "$f"; done |
  tar --null -T - -cf - | tar -xf - -C "$tmp"

mkdir -p "$tmp/internal/genfixture"
cp "$fx/hello.templ.fixture" "$tmp/internal/genfixture/hello.templ"
mkdir -p "$tmp/internal/genfixture/queries"
cp "$fx/schema.sql" "$tmp/internal/genfixture/"
cp "$fx/query.sql" "$tmp/internal/genfixture/queries/"
# The fixture sqlc.yaml replaces the repo's own config, so the repo's committed sqlc output would
# look orphaned to generate-check. Drop every sqlc-generated file, detected by its header (same
# marker generate-check.sh keys on) rather than a hard-coded path; the fixture output is regenerated.
while IFS= read -r f; do rm -f "$f"; done < <(
  grep -rlE --include='*.go' --exclude-dir=.git '^// Code generated by sqlc\. DO NOT EDIT\.$' "$tmp" || true
)
cp "$fx/sqlc.yaml" "$tmp/sqlc.yaml"

cd "$tmp" || exit 1
make -s generate >/dev/null 2>&1 || bad "make generate failed"
[ -f internal/genfixture/hello_templ.go ] || bad "templ output missing"
[ -f internal/genfixture/db/query.sql.go ] || bad "sqlc output missing"

make -s generate-check >/dev/null 2>&1 || bad "generate-check fails right after generate"

printf '\ntempl Bye() {\n\t<p>bye</p>\n}\n' >> internal/genfixture/hello.templ
make -s generate-check >/dev/null 2>&1 && bad "generate-check missed a stale templ file"

printf '\n-- name: ListItems :many\nSELECT id, name FROM items;\n' >> internal/genfixture/queries/query.sql
make -s generate-check >/dev/null 2>&1 && bad "generate-check missed a stale sqlc query"

make -s generate-check >/dev/null 2>&1 || bad "generate-check still fails after regenerating"

# A removed query file leaves an orphaned output that sqlc does not delete.
printf -- '-- name: CountItems :one\nSELECT count(*) FROM items;\n' > internal/genfixture/queries/extra.sql
make -s generate >/dev/null 2>&1 || bad "make generate failed with extra query"
[ -f internal/genfixture/db/extra.sql.go ] || bad "sqlc output for extra query missing"
rm internal/genfixture/queries/extra.sql
make -s generate-check >/dev/null 2>&1 && bad "generate-check missed an orphaned sqlc output"
[ -f internal/genfixture/db/extra.sql.go ] && bad "orphaned sqlc output not removed"

make -s generate-check >/dev/null 2>&1 || bad "generate-check still fails after removing the orphan"

cd "$root"
[ "$fail" = 0 ] && echo "generate-test: ok"
exit "$fail"
