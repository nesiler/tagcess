#!/usr/bin/env bash
# Generates OpenCode subagents (.opencode/agent/*.md) from .agents/agents/*.md (the single source).
# Usage: gen-opencode-agents.sh [OUT_DIR]   (default .opencode/agent)
# The model is not set: a subagent uses the session's model. Reviews that must be independent of a
# cheap model are separate coordinator sessions (docs/development.md).
set -eu
cd "$(dirname "$0")/.."
. scripts/lib.sh

out=${1:-.opencode/agent}
mkdir -p "$out"
# Remove only files this script generated, never other Markdown in OUT_DIR.
for f in "$out"/*.md; do
  [ -f "$f" ] && grep -q 'GENERATED by scripts/gen-opencode-agents.sh' "$f" && rm -f "$f"
done

yaml_str() { printf '%s' "$1" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g'; }

for f in .agents/agents/*.md; do
  name=$(fm "$f" name); desc=$(fm "$f" description); sandbox=$(fm "$f" codex_sandbox)
  [ -n "$name" ] && [ -n "$desc" ] || { echo "agents: $f needs name and description" >&2; exit 1; }
  edit=deny
  [ "${sandbox:-read-only}" = read-only ] || edit=allow
  {
    echo "---"
    echo "description: \"$(yaml_str "$desc")\""
    echo "mode: subagent"
    echo "permission:"
    echo "  edit: $edit"
    echo "---"
    echo "<!-- GENERATED by scripts/gen-opencode-agents.sh from $f. Do not edit; run 'make agents'. -->"
    body "$f" | sed -e '/./,$!d'
  } > "$out/$name.md"
done
